#Comparison Operators
"""
comparison operators are used to cpmpara two values:

Operator Equal(==)

Operator Not Equal(|=)

Operator Greater than(>)

Operator Less than(<)

Operator Greater than or equal to(>=)

Operator Less than or equal to(<=)
"""
#Ex. with Operator Equal (==)
a="30"
b='30'
print(a==b)

#Ex. Operator Not Equal(!=)
print(a!=b)

#Ex. Operator Greater than(>)
a="20"
b="39"
print(a>b)

#Ex. Operator Less than(<)
print(a<b)

#Ex. Operator Greater than or equal to(>=)
print(a>=b)

#Ex. Operator Less than or equal to(<=)
print(a<=b)
